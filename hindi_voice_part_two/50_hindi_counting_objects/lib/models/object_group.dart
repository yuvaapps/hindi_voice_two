class ObjectGroup {
  final int id;
  final int count;
  final String objectHindi;
  final String objectEnglish;
  final String objectHindiSingular;
  final String objectEnglishSingular;
  final String tamil;
  final String emoji;
  final String numAudio;
  final String hindiDevanagari;
  final String hindiName;
  final String roman;
  final String category;

  const ObjectGroup({
