    required this.count,
    required this.objectHindi,
    required this.objectEnglish,
    required this.objectHindiSingular,
    required this.objectEnglishSingular,
    required this.tamil,
    required this.emoji,
    required this.numAudio,
    required this.hindiDevanagari,
    required this.hindiName,
    required this.roman,
    required this.category,
  });
}
